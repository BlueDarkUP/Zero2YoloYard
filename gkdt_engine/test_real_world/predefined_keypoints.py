def get_predefined_keypoints(object_name):
    """Return a copy of the schema for an object or dataset name, if known."""
    object_name = object_name.strip().lower()
    schema = PREDEFINED_KEYPOINTS.get(object_name)
    if schema is None:  # trial 1
        object_name_with_subscript = object_name.replace(' ', '_')
        schema = PREDEFINED_KEYPOINTS.get(object_name_with_subscript)
    if schema is None:  # trial 2
        object_name_with_whitespace = object_name.replace('_', ' ')
        schema = PREDEFINED_KEYPOINTS.get(object_name_with_whitespace)
    if schema is None:  # trial 3, matching a substring
        normalized_name = object_name.casefold()
        for known_name, known_schema in PREDEFINED_KEYPOINTS.items():
            if normalized_name in known_name.casefold():  # if known_name contains normalized_name
                schema = known_schema
                break
    return deepcopy(schema) if schema is not None else None


def get_prompt_info(object_name, kps_texts, support_im_path, support_kps, skeleton):
    """Resolve prompts for one object using user input before predefined data.

    Predefined prompts are only used when the user supplied neither text nor a
    visual prompt. This keeps visual-only inference free of unrelated text
    prompts and follows the N_t/N_v convention used by the single-object demo.
    """
    kps_texts = list(kps_texts)
    skeleton = list(skeleton)
    N_t = len(kps_texts)
    N_v = len(support_kps) // 2 if support_im_path and support_kps else 0

    if (N_t == 0) and (N_v == 0) and (object_name != '') and (object_name != 'object1'):
        predefined_schema = get_predefined_keypoints(object_name)
        if predefined_schema is not None:
            kps_texts = predefined_schema['keypoints']
            if not skeleton:
                skeleton = [node for edge in predefined_schema['skeleton'] for node in edge]
            N_t = len(kps_texts)
            print(f'Found predefined keypoints for object type {object_name}: {kps_texts}')
        else:
            print(f'No predefined keypoints for object type {object_name}.')

    assert N_t > 0 or N_v > 0, (
        f'At least text or visual prompts are required for {object_name}.'
    )
    if N_t > 0 and N_v > 0:
        assert N_v == N_t, (
            f'Visual and textual prompt counts must match for {object_name}.'
        )
    return kps_texts, skeleton, N_t, N_v


